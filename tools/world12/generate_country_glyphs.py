"""Render tiny country masks from the pinned public-domain Natural Earth source.

Input: ne_50m_admin_0_map_subunits.geojson, SHA-256 below.
No image-generation service or runtime geographic library is required.
"""
import hashlib
import json
import math
from pathlib import Path
import sys

SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_map_subunits.geojson"
SHA256 = "b1df8433477614c89e6b724990a7ab3733ec647559863321b6255c3fa3fce3ec"
WIDTH, HEIGHT = 22, 34


def inside(x, y, ring):
    result = False
    for (ax, ay), (bx, by) in zip(ring, ring[1:] + ring[:1]):
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            result = not result
    return result


def mask(feature):
    geometry = feature["geometry"]
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    project = lambda point: (math.radians(point[0]), math.log(math.tan(math.pi / 4 + math.radians(point[1]) / 2)))
    projected = [[[project(point) for point in ring] for ring in polygon] for polygon in polygons]
    points = [point for polygon in projected for ring in polygon for point in ring]
    xmin, xmax = min(p[0] for p in points), max(p[0] for p in points)
    ymin, ymax = min(p[1] for p in points), max(p[1] for p in points)
    scale = min((WIDTH - 1) / (xmax - xmin), (HEIGHT - 1) / (ymax - ymin))
    ox, oy = (WIDTH - scale * (xmax - xmin)) / 2, (HEIGHT - scale * (ymax - ymin)) / 2
    rows = []
    for y in range(HEIGHT):
        row = 0
        for x in range(WIDTH):
            px, py = xmin + (x + .5 - ox) / scale, ymax - (y + .5 - oy) / scale
            if any(inside(px, py, polygon[0]) and not any(inside(px, py, hole) for hole in polygon[1:]) for polygon in projected):
                row |= 1 << x
        rows.append(row)
    return rows


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_country_glyphs.py <source.geojson> <output.hpp>")
    raw = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise SystemExit("source SHA-256 does not match the documented map revision")
    features = json.loads(raw)["features"]
    out = ["// SPDX-License-Identifier: GPL-3.0-only", "// Generated by tools/world12/generate_country_glyphs.py; do not edit.",
           "// Geographic masks: Natural Earth, public domain.", f"// Source: {SOURCE}",
           f"// SHA-256: {SHA256}", "// https://www.naturalearthdata.com/about/terms-of-use/",
           "#pragma once", "#include <array>", "#include <cstdint>", "namespace bmh::ui::country_glyphs {",
           f"inline constexpr int width={WIDTH},height={HEIGHT};"]
    for name in ("England", "Germany"):
        feature = next(f for f in features if f["properties"]["NAME"] == name)
        out.append(f"inline constexpr std::array<uint32_t,{HEIGHT}> {name.lower()}={{")
        out.extend(f"    0b{row:0{WIDTH}b}u," for row in mask(feature))
        out.append("};")
    out.append("}")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
