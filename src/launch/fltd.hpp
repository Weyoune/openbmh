#pragma once
// The English "Football Limited" (FLTD.EXE) as data for the one OpenBMH engine.
//
// The engine reads its data the German way: BMH.EXE tables at German addresses, TEXTD.BLK and
// M3D.MAN. prepare_english_game() turns an English installation into such a data directory,
// once, in the launcher cache:
//   - TEXTE.BLK -> TEXTD.BLK and M3E.MAN -> M3D.MAN (same formats, the text slots are the
//     same variables; docs/formats/TEXTD_INVENTORY.md),
//   - FLTD.EXE -> "BMH.exe" in the OpenBMH image format (formats/le.hpp): an image in the
//     German address space. Every German data object the engine reads is filled from its
//     English counterpart (src/launch/fltd_map.inc, generated by runtime verification), German
//     numbers keep V2.24 features the English V2.20 lacks, OpenBMH's own English texts
//     stand in for V2.24 texts, and the whole English data segment also lies at its own
//     addresses so that English pointers stay valid. Then the rule base is applied.
//   - the pictures, fonts, sounds and the other data files are copied unchanged.
// The English league structure (20 20 20 20 10 + the four international leagues of 12)
// arrives through the size table at LeagueSizes and is installed by the career session.
// Background: runtime verification

#include <filesystem>
#include <string>

#include "formats/le.hpp"

namespace bmh::launch {

// The German-layout image of FLTD.EXE (throws std::runtime_error for another file).
LeImage translate_fltd(const std::filesystem::path& fltd_exe, bool apply_supported_rules = true);

// Builds the German-layout data directory `target` from the English game in `source`.
// Returns false with `error` set when a file cannot be read or written.
bool prepare_english_game(const std::filesystem::path& source, const std::filesystem::path& target, std::string& error);

}  // namespace bmh::launch
