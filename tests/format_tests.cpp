static void test_savegame(const fs::path& data) {
    Savegame s = load_savegame(bmh::test::external_input("format-start.fbm"));
    CHECK(s.version == "V2.24");
    CHECK(s.checksum_ok);
    CHECK(s.stream.size() == 165311);

    // The block table must reproduce the stream length exactly (125 state blocks + 4 pools).
    SaveState st(s.stream);
    CHECK(st.blocks().size() == 125);

    // Compare decoded records with an explicitly supplied external expectation table.
    std::ifstream player_input(bmh::test::external_input("format-players.tsv"));
    CHECK(bool(player_input));
    size_t id; int condition, technique, form, age, position, strength;
    size_t checked = 0;
    while (player_input >> id >> condition >> technique >> form >> age >> position >> strength) {
        const Player p{"", le32(s.stream, st.block(::bmh::layout::PlayerConditionTechniqueForm).offset + id * 4),
            le32(s.stream, st.block(::bmh::layout::PlayerSkillWords).offset + id * 4),
            le32(s.stream, st.block(::bmh::layout::PlayerIdentityWords).offset + id * 4)};
        CHECK(p.condition() == condition && p.technique() == technique && p.form() == form &&
              p.age() == age && p.position() == position && p.strength() == strength);
        ++checked;
    }
    CHECK(player_input.eof() && checked > 0);

    // encrypt/decrypt roundtrip
    Bytes copy = s.stream;
    fbm_encrypt(copy.data(), copy.size(), s.key);
    fbm_decrypt(copy.data(), copy.size(), s.key);
    CHECK(copy == s.stream);
}

// Club name of a team id in a running game: offset table *ClubIdentities into the club name pool.
static std::string team_name(const SaveState& st, int team) {
    const Bytes& pool = st.pool(0);
    size_t ofs = le16(Bytes(st.data(::bmh::layout::ClubIdentities) + team * 2, st.data(::bmh::layout::ClubIdentities) + team * 2 + 2), 0);
    return iso646de_to_utf8(reinterpret_cast<const char*>(pool.data() + ofs));
}

static void test_schedule(const fs::path& data) {
    // Round strings: every round is a perfect matching of the league's teams.
    for (int teams : {18, 20, 16, 12, 6, 4}) {
        for (int md = 1; md <= 2 * (teams - 1); md++) {
            std::vector<int> seen(teams, 0);
            for (const Fixture& f : generate_fixtures(teams, md, teams - 1, 0)) {
                seen.at(f.home)++;
                seen.at(f.away)++;
            }
            for (int n : seen) CHECK(n == 1);
        }
    }
    // Second half repeats the first with home and away swapped.
    auto first = league_fixtures(0, 1), second = league_fixtures(0, 18);
    CHECK(first[0].home == second[0].away && first[0].away == second[0].home);

    // Team order of the recorded career (clubs are shuffled when a new game starts).
    Savegame s = load_savegame(bmh::test::external_input("format-start.fbm"));
    SaveState st(s.stream);
    CHECK(team_name(st, 0) == bmh::test::expected_text("format.text.5"));
    CHECK(team_name(st, 14) == bmh::test::expected_text("format.text.2"));
    CHECK(team_league(14) == 0 && team_league(90) == 5 && team_league(138) == kLeagueCount);
    // Before the season every result is "not played".
    const uint8_t* results = st.data(::bmh::layout::LeagueResults);
    for (size_t i = 0; i < kResultsSize; i++) CHECK(!decode_result(results[i]).played);
}

// Matchday 1 of the Bundesliga as shown by the original (docs/REFERENCE.md).
static void test_matchday1(const fs::path& refs) {
    Savegame s = load_savegame(refs / "SP2VOR.FBM");
    CHECK(s.checksum_ok);
    SaveState st(s.stream);
    struct Expected { std::string home, away; int hg, ag; };
    std::ifstream expected_input(bmh::test::external_input("format-matches.tsv"));
    std::vector<Expected> expected;
    for (std::string line; std::getline(expected_input, line);) {
        std::istringstream row(line); Expected value;
        std::getline(row, value.home, '\t'); std::getline(row, value.away, '\t');
        if (!(row >> value.hg >> value.ag)) throw std::runtime_error("Invalid match expectation");
        expected.push_back(std::move(value));
    }
    CHECK(expected.size() == 9);
    auto fixtures = league_fixtures(0, 1);
    CHECK(fixtures.size() == 9);
    for (size_t m = 0; m < fixtures.size() && m < 9; m++) {
        Result r = decode_result(st.data(::bmh::layout::LeagueResults)[result_index(0, 1, m)]);
        bool ok = team_name(st, fixtures[m].home) == expected[m].home && team_name(st, fixtures[m].away) == expected[m].away &&
                  r.played && r.home_goals == expected[m].hg && r.away_goals == expected[m].ag;
        if (!ok) std::printf("  match %zu: %s - %s %d:%d\n", m, team_name(st, fixtures[m].home).c_str(),
                             team_name(st, fixtures[m].away).c_str(), r.home_goals, r.away_goals);
        CHECK(ok);
    }
    // Matchday 2 has not been played yet.
    CHECK(!decode_result(st.data(::bmh::layout::LeagueResults)[result_index(0, 2, 0)]).played);
}

// Team values K/T/F/M/Ø right before matchday 1. The original showed them on the results
// screen at 90'; for these nine teams nothing changed during their match, so the values
// equal the pre-match ones. Ø is also the "Stärke" shown on the desktop (Bayern 84,
// Frankfurt 91 before the match).
static void test_team_values(const fs::path& refs) {
    Savegame s = load_savegame(refs / "SP1VOR.FBM");
    SaveState st(s.stream);
    GameState g = GameState::from_save(st);
    using namespace avg;
    const uint16_t lineup = LINEUP_ONLY | ALL_POSITIONS;
    struct Expected { int team, k, t, f, m, strength; };
    std::ifstream expected_input(bmh::test::external_input("format-team-values.tsv"));
    std::vector<Expected> expected;
    for (Expected value; expected_input >> value.team >> value.k >> value.t >> value.f >> value.m >> value.strength;)
        expected.push_back(value);
    CHECK(expected_input.eof() && !expected.empty());
    for (const Expected& e : expected) {
        CHECK(team_average(g, e.team, lineup | CONDITION).value == e.k);
        CHECK(team_average(g, e.team, lineup | TECHNIQUE).value == e.t);
        CHECK(team_average(g, e.team, lineup | FORM).value == e.f);
        CHECK(team_average(g, e.team, lineup | MORALE).value == e.m);
        CHECK(team_average(g, e.team, lineup | CONDITION | TECHNIQUE | FORM | MORALE).value == e.strength);
    }
}

int main(int argc, char** argv) {
    test_random();
    test_generated_formats();
    if (argc < 2) {
        std::printf("no data directory given, skipping data tests\n");
    } else {
        fs::path data = argv[1];
        try {
            test_images(data);
            test_fonts_and_text(data);
            test_database(data);
            test_executable(data);
            test_savegame(data);
            test_schedule(data);
            if (argc >= 3 && *argv[2]) test_matchday1(argv[2]), test_team_values(argv[2]);
            else std::printf("no reference directory given, skipping matchday tests\n");
        } catch (const std::exception& ex) {
            std::printf("FAIL exception: %s\n", ex.what());
            failures++;
        }
    }
    std::printf(failures ? "%d FAILURE(S)\n" : "all tests passed\n", failures);
    return failures ? 1 : 0;
}
